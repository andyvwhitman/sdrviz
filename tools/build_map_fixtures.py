"""Bundle the seed and sim files the Map mockup reads into one file:// twin.

Chromium blocks fetch() on file://, so mockups read data from JS twins that
register ``window.SDRVIZ_DATA[<repo path>]`` (design/spec.md §8.4). The seed
and sim generators do not write twins for these two files yet, so this writes
``design/mockups/map-fixtures.js`` with them verbatim. Re-run it after
``tools/gen_sim.py``:

    python3 tools/build_map_fixtures.py
"""

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SOURCES = ["data/seed/places.json", "data/sim/routes.json"]
OUT = REPO / "design" / "mockups" / "map-fixtures.js"


def main() -> None:
    lines = [
        "/* Generated by tools/build_map_fixtures.py. Do not edit; re-run the tool. */",
        "window.SDRVIZ_DATA = window.SDRVIZ_DATA || {};",
    ]
    for path in SOURCES:
        data = json.loads((REPO / path).read_text(encoding="utf-8"))
        text = json.dumps(data, separators=(",", ":"), ensure_ascii=False)
        lines.append(f'window.SDRVIZ_DATA["{path}"] = {text};')
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({OUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
